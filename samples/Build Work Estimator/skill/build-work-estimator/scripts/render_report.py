"""Render a build estimate as Markdown and PDF.

Author: Dewain Robinson

    python render_report.py estimate.json -o report --format both

PDF generation failing must never lose the estimate: the Markdown is written
first, and a missing Playwright or Chromium is reported with its remediation
rather than raised.
"""

