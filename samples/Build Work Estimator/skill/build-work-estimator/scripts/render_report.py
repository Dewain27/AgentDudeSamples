NOT_A_COMPARISON = """> **This is not a stack comparison tool.** It reports one build stack, in that
> stack's own currency. Technology stack decisions are not made on cost alone —
> capability, existing skills, governance, integration, and support all matter
> more than a build-time figure — and using this report to pick a stack would
> be using it for something it was not designed to answer."""

AUTHOR = "Dewain Robinson"

DISCLAIMER = """> ### SAMPLE — BUILD ESTIMATE ONLY, NOT A QUOTE
>
> This document is generated by a **sample estimator** published as a
> demonstration of *how* an organization could build one. It is not a quote, a
> bid, a budget authority, or a commitment of any kind.
>
> **It estimates the work of building only — never the cost of running what
> gets built.** Runtime, end-user licences, infrastructure, and human labour
> are all outside its scope and are not represented in any figure below.
>
> **The figures are estimates and will be wrong.** They are derived from
> historical consumption patterns that may not resemble the work being
> estimated. Observed cost for comparable work in the calibration data spans
> more than 100x between the cheapest and most expensive instances. Treat the
> range as the estimate; treat the point figure as the midpoint of a guess.
>
> **Before any real budgeting use, this estimator must be modified for your
> organization** — recalibrated against your own usage history, repriced
> against your contracted rates rather than list price, and adjusted for your
> own delivery patterns, model choices, and review overhead.
>
> Rates verified {rate_date} and change without notice.
> Calibration source: `{calibration_source}` · Generated {timestamp}"""

FOOTER = ("SAMPLE — build estimate only, not a quote. Excludes runtime cost. "
          "Modify for your organization before budgeting use.")

SCOPE_TABLE = """| Out of scope | Where to go instead |
| --- | --- |
| Runtime / operational cost of what gets built | [Copilot Studio agent usage estimator](https://microsoft.github.io/copilot-studio-estimator/) |
| End-user seat licences (M365 Copilot, Power Platform) | Your licensing/procurement process |
| Infrastructure, hosting, storage, egress | Your cloud cost tooling |
| Human labour — PM, design, QA time | Your delivery estimation process |
| Ongoing maintenance and support after delivery | A run cost, not a build cost |"""


def money(value):
    return "$" + format(round(float(value), 2), ",.2f")


def build_header(result):
    """Front matter, title, disclaimer, and the stack/scope banners."""
    out = []
    out.append("---")
    out.append("title: Build Work Estimate — %s" % result["project"])
    out.append("author: %s" % AUTHOR)
    out.append("build_stack: %s" % result["build_stack"])
    out.append("estimate_id: %s" % result["estimate_id"])
    out.append("generated: %s" % result["generated"])
    out.append("---")
    out.append("")
    out.append("# Build Work Estimate — %s" % result["project"])
    out.append("")
    out.append("**Author:** %s · **Estimate id:** `%s` · **Generated:** %s"
               % (AUTHOR, result["estimate_id"], result["generated"]))
    out.append("")
    out.append(DISCLAIMER.format(
        rate_date=rates.ANTHROPIC_VERIFIED,
        calibration_source=(result.get("profile") or {}).get(
            "source", "not applicable"),
        timestamp=result["generated"]))
    out.append("")
    out.append("## Build stack — %s" % result["stack_label"])
    out.append("")
    out.append("**Metered in: %s.** %s"
               % (result["stack_currency"], result["stack_note"]))
    out.append("")
    out.append("> The currency is decided by what you **build with**, not what "
               "you build **for**.\n> Building a Microsoft workload with Claude "
               "Code is metered in tokens; building\n> it in Copilot Studio is "
               "metered in Copilot Credits.")
    out.append("")
    out.append(NOT_A_COMPARISON)
    out.append("")
    out.append("## Scope — this estimates the build, not the run")
    out.append("")
    out.append("This figure covers the work of **building** the thing. It does "
               "not\ncover operating it afterwards.")
    out.append("")
    out.append(SCOPE_TABLE)
    out.append("")
    return out


def build_stack_markdown(result):
    """Report for a non-Claude-Code stack, in that stack's own currency."""
    out = build_header(result)
    detail = result["stack_detail"]

    if result["build_stack"] == "copilot-studio":
        out.append(copilot_credits.render_markdown(detail))
    else:
        out.append(github_copilot.render_markdown(detail))

    licence = result.get("licensing") or {}
    if licence.get("model") == licensing.SEAT:
        out.append("## Licensing")
        out.append("")
        out.append("**Seat / allowance-based licensing (%s).** The consumption "
                   "above draws on an\nallowance already paid for. No "
                   "additional money changes hands until the\nallowance is "
                   "exhausted — but the allowance itself was bought, so the "
                   "capacity\nthis build uses up has a real cost."
                   % (licence.get("plan") or "unspecified"))
        out.append("")
        if licence.get("seat_monthly_cost"):
            out.append("Seat cost: **$%s/month** × %d seat%s. Committed to "
                       "other work: **%.0f%%**."
                       % (format(licence["seat_monthly_cost"], ",.2f"),
                          licence.get("seats", 1),
                          "" if licence.get("seats", 1) == 1 else "s",
                          licence.get("other_workload_share", 0) * 100))
            out.append("")
    else:
        out.append("## Licensing")
        out.append("")
        out.append("**Consumption billing.** Every unit consumed is billed, so "
                   "the figures above\nare the expected charge.")
        out.append("")

    out.append("## Known limits")
    out.append("")
    out.append("1. **Build only.** Says nothing about what the built thing "
               "costs to run.")
    out.append("2. **Rates go stale.** Verified %s; re-verify against the "
               "sources above." % rates.COPILOT_VERIFIED)
    out.append("3. **This is a sample.** Modify it for your organization "
               "before budgeting use.")
    out.append("")
    for warning in result.get("warnings") or []:
        out.append("> WARNING: %s" % warning)
    if result.get("warnings"):
        out.append("")
    out.append("## Close the loop")
    out.append("")
    out.append("```")
    out.append("python record_actual.py %s --sessions <session-id> [...]"
               % result["estimate_id"])
    out.append("```")
    out.append("")
    out.append("---")
    out.append("")
    out.append("*%s*" % FOOTER)
    out.append("")
    return "\n".join(out)


def build_markdown(result, credits=None):
    if result.get("stack_detail") is not None:
        return build_stack_markdown(result)
    p = result["profile"]
    source = p["source"]
    if source == "measured":
        basis = ("Measured from %d local session%s%s."
                 % (p["sessions"], "" if p["sessions"] == 1 else "s",
                    (" spanning %s to %s" % tuple(p["date_range"]))
                    if p.get("date_range") else ""))
    else:
        basis = ("**Published baselines — no local session history was found.** "
                 "This is materially less reliable than a measured profile. "
                 "Run `calibrate.py` after some real work to improve it.")

    out = build_header(result)
    out.append("## Summary")
    out.append("")
    out.append("| | Amount |")
    out.append("| --- | ---: |")
    out.append("| Base estimate | %s |" % money(result["base"]))
    out.append("| Reserve (%.0f%%) | %s |"
               % (result["reserve_percent"], money(result["reserve"])))
    out.append("| **Budget ask** | **%s** |" % money(result["budget_ask"]))
    out.append("| Observed low | %s |" % money(result["low"]))
    out.append("| Observed high | %s |" % money(result["high"]))
    out.append("")

    a = result["adequacy"]
    out.append("## Reserve adequacy")
    out.append("")
    if a["covers_high"]:
        out.append("A **%.0f%%** reserve brings the budget ask to %s, which "
                   "covers the observed high of %s for comparable work."
                   % (a["reserve_percent"], money(a["budget_ask"]),
                      money(a["high"])))
    else:
        out.append("**The reserve does not cover observed variance.**")
        out.append("")
        out.append("A **%.0f%%** reserve brings the budget ask to %s. "
                   "Comparable work in the\ncalibration data has reached %s. "
                   "Full coverage would require **%.0f%%**."
                   % (a["reserve_percent"], money(a["budget_ask"]),
                      money(a["high"]), a["required_percent"]))
        out.append("")
        out.append("This is the single most likely way this estimate causes a "
                   "problem: not that the\npoint figure is wrong, but that the "
                   "contingency carried on top of it is too thin\nfor how wide "
                   "the real spread is.")
    out.append("")

    out.append("## Breakdown")
    out.append("")
    out.append("| Item | Size | Files | Unknowns | Turns | Estimate | Range | n |")
    out.append("| --- | --- | ---: | ---: | ---: | ---: | --- | ---: |")
    for row in result["items"]:
        out.append("| %s | %s%s | %d | %d | %s | %s | %s – %s | %d |"
                   % (row["name"], row["size"],
                      " (brownfield)" if row["brownfield"] else "",
                      row["files"], row["unknowns"],
                      format(row["turns"], ","), money(row["cost"]),
                      money(row["low"]), money(row["high"]), row["n"]))
    out.append("")
    if result.get("thin_buckets"):
        out.append("> **Thin calibration data.** These size classes have fewer "
                   "than 3 recorded\n> sessions behind them: **%s**. Their "
                   "medians are weak and the corresponding\n> figures above "
                   "should be treated as little better than a guess."
                   % ", ".join(result["thin_buckets"]))
        out.append("")

    out.append("## Calibration basis")
    out.append("")
    out.append(basis)
    out.append("")
    out.append("Cost per agent turn: **%s**. Rates are **list price** — an "
               "organization on\ncontracted rates must substitute its own."
               % money(p["cost_per_main_turn"]))
    out.append("")
    if result.get("corrections"):
        out.append("### Correction factors from recorded actuals")
        out.append("")
        out.append("| Bucket | n | Observed ratio | Applied (shrunk) | In effect |")
        out.append("| --- | ---: | ---: | ---: | --- |")
        for c in result["corrections"]:
            out.append("| %s | %d | %.2fx | %.2fx | %s |"
                       % (c["bucket"], c["n"], c["median_ratio"] or 1.0,
                          c["shrunk_ratio"], "yes" if c["applied"] else
                          "no — provisional"))
        out.append("")
        out.append("Observed ratios are shrunk toward 1.0 in proportion to "
                   "sample size, so a single\nrecorded actual cannot swing "
                   "future estimates.")
        out.append("")

    if result.get("licensing"):
        out.append(licensing.render_markdown(result["licensing"]))

    out.append("## Assumptions and sensitivities")
    out.append("")
    out.append("- Turn counts come from the calibration profile, and are the "
               "weakest input in\n  this model. Where `n` is small, treat the "
               "figure as indicative only.")
    out.append("- Cost scales with context size and turn count. Session "
               "hygiene — clearing between\n  unrelated tasks — moves the "
               "number more than most scope changes do.")
    out.append("- Brownfield work is scaled by %.1fx over greenfield."
               % 1.5)
    out.append("- Each declared unknown widens the upper bound by 25%.")
    out.append("")
    for warning in result.get("warnings") or []:
        out.append("> WARNING: %s" % warning)
    if result.get("warnings"):
        out.append("")

    out.append("## Known limits")
    out.append("")
    out.append("1. **Build only.** Says nothing about what the built thing "
               "costs to run.")
    out.append("2. **Turn counts are the weakest input**, and thin buckets are "
               "flagged above.")
    out.append("3. **List pricing only.** Contracted rates must be substituted.")
    out.append("4. **This machine only.** Sessions from other devices are not "
               "visible.")
    out.append("5. **Rates go stale.** Both providers change pricing without "
               "notice.")
    out.append("")
    out.append("## Close the loop")
    out.append("")
    out.append("When this build is done, record what it actually cost. That is "
               "how the estimator\ngets better — and without it, it cannot.")
    out.append("")
    out.append("```")
    out.append("python record_actual.py %s --sessions <session-id> [...]"
               % result["estimate_id"])
    out.append("```")
    out.append("")
    out.append("---")
    out.append("")
    out.append("*%s*" % FOOTER)
    out.append("")
    return "\n".join(out)


