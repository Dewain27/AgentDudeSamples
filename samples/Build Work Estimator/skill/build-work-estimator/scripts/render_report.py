def write_pdf(md_text, pdf_path, title):
    """Render Markdown to PDF. Returns None on success, or a reason string."""
    try:
        import markdown as md_lib
    except ImportError:
        return ("the `markdown` package is not installed "
                "(pip install markdown)")
    try:
        from playwright.sync_api import sync_playwright
    except ImportError:
        return ("Playwright is not installed "
                "(pip install playwright && playwright install chromium)")

    body = md_lib.markdown(md_text, extensions=["tables", "fenced_code"])
    html = ("<!doctype html><html><head><meta charset='utf-8'>"
            "<title>%s</title><meta name='author' content='%s'>"
            "<style>%s</style></head><body>%s</body></html>"
            % (title, AUTHOR, CSS, body))

    try:
        with sync_playwright() as pw:
            browser = pw.chromium.launch()
            try:
                page = browser.new_page()
                page.set_content(html, wait_until="load")
                page.pdf(path=pdf_path, format="Letter",
                         print_background=True,
                         display_header_footer=True,
                         header_template="<div></div>",
                         footer_template=FOOTER_TEMPLATE,
                         margin={"top": "0.7in", "bottom": "0.8in",
                                 "left": "0.75in", "right": "0.75in"})
            finally:
                browser.close()
    except Exception as exc:
        return "Chromium could not render the PDF (%s). Try: playwright install chromium" % exc
    return None


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("estimate_json")
    ap.add_argument("-o", "--out", default="build-work-estimate")
    ap.add_argument("--format", choices=["md", "pdf", "both"], default="both")
    ap.add_argument("--credits-json", default=None)
    args = ap.parse_args(argv)

    with open(args.estimate_json, "r") as fh:
        result = json.load(fh)
    credits = None
    if args.credits_json:
        with open(args.credits_json, "r") as fh:
            credits = json.load(fh)

    md_text = build_markdown(result, credits)
    written = []

    if args.format in ("md", "both"):
        md_path = args.out + ".md"
        with open(md_path, "w") as fh:
            fh.write(md_text)
        written.append(md_path)
        print("Wrote %s" % md_path)

    if args.format in ("pdf", "both"):
        if args.format == "pdf":
            # Always leave the Markdown behind: the estimate must survive a
            # PDF toolchain failure.
            md_path = args.out + ".md"
            with open(md_path, "w") as fh:
                fh.write(md_text)
            written.append(md_path)
        pdf_path = args.out + ".pdf"
        reason = write_pdf(md_text, pdf_path,
                           "Build Work Estimate - %s" % result["project"])
        if reason:
            print("WARNING  PDF not generated: %s" % reason)
            print("         The Markdown estimate at %s is complete."
                  % (args.out + ".md"))
            print("         On a host that creates documents natively "
                  "(Copilot Cowork, Claude Cowork,")
            print("         Copilot Studio), ask it to produce the PDF from "
                  "that Markdown rather")
            print("         than installing a browser.")
        else:
            written.append(pdf_path)
            print("Wrote %s" % pdf_path)

    return 0


if __name__ == "__main__":
    sys.exit(main())
